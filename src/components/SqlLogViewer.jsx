import React, { useState } from 'react';
import { Database, Terminal, ChevronUp, ChevronDown, Trash2, Copy, Check } from 'lucide-react';

export default function SqlLogViewer({ sqlLogs, onClearLogs }) {
  const [isOpen, setIsOpen] = useState(false);
  const [copiedIndex, setCopiedIndex] = useState(null);

  const handleCopy = (sqlText, idx) => {
    navigator.clipboard.writeText(sqlText);
    setCopiedIndex(idx);
    setTimeout(() => setCopiedIndex(null), 2000);
  };

  return (
    <div className="fixed bottom-0 left-0 right-0 z-40 px-4 pb-2 no-print">
      <div className="max-w-7xl mx-auto">
        <div className="glass-panel border border-sky-300 rounded-2xl shadow-xl overflow-hidden bg-slate-950 text-sky-100">
          
          {/* Header Toggle Bar */}
          <button
            onClick={() => setIsOpen(!isOpen)}
            className="w-full px-4 py-2.5 flex items-center justify-between bg-slate-900/90 hover:bg-slate-900 transition-all text-xs font-mono border-b border-slate-800"
          >
            <div className="flex items-center gap-2.5">
              <Terminal className="h-4 w-4 text-sky-400 animate-pulse" />
              <span className="font-bold text-sky-300">Live Database SQL Execution Log</span>
              <span className="px-2 py-0.5 rounded-full text-[10px] bg-sky-900/80 text-sky-200 border border-sky-700 font-sans font-bold">
                {sqlLogs.length} Queries Executed
              </span>
            </div>

            <div className="flex items-center gap-3">
              {sqlLogs.length > 0 && (
                <span className="text-[11px] text-sky-400 font-sans truncate max-w-md hidden md:inline">
                  Last Query: <code className="text-emerald-400 font-mono">{sqlLogs[0]?.sql}</code>
                </span>
              )}
              {isOpen ? <ChevronDown className="h-4 w-4 text-sky-400" /> : <ChevronUp className="h-4 w-4 text-sky-400" />}
            </div>
          </button>

          {/* Drawer Body */}
          {isOpen && (
            <div className="p-4 space-y-3 max-h-72 overflow-y-auto bg-slate-950/95 font-mono text-xs">
              <div className="flex items-center justify-between text-[11px] text-slate-400 font-sans pb-2 border-b border-slate-800">
                <span>Real-time MySQL statements generated by frontend user form interactions</span>
                <button
                  onClick={onClearLogs}
                  className="flex items-center gap-1 text-rose-400 hover:text-rose-300 font-semibold text-[10px]"
                >
                  <Trash2 className="h-3 w-3" />
                  <span>Clear SQL Terminal</span>
                </button>
              </div>

              {sqlLogs.length === 0 ? (
                <div className="text-slate-500 py-4 text-center font-sans text-xs">
                  No frontend database queries executed yet. Fill out forms in the Student or Faculty portals to see real-time SQL statements!
                </div>
              ) : (
                <div className="space-y-2">
                  {sqlLogs.map((log, idx) => (
                    <div key={idx} className="p-2.5 rounded-xl bg-slate-900 border border-slate-800 flex items-start justify-between gap-3 hover:border-sky-800 transition-all">
                      <div className="space-y-1 flex-1 overflow-x-auto">
                        <div className="flex items-center gap-2 text-[10px]">
                          <span className={`px-1.5 py-0.5 rounded font-extrabold ${
                            log.action === 'INSERT' ? 'bg-emerald-950 text-emerald-400 border border-emerald-800' :
                            log.action === 'UPDATE' ? 'bg-blue-950 text-blue-400 border border-blue-800' :
                            'bg-amber-950 text-amber-400 border border-amber-800'
                          }`}>
                            {log.action}
                          </span>
                          <span className="text-slate-400">TABLE:</span>
                          <span className="text-sky-300 font-bold">{log.table}</span>
                          <span className="text-slate-500">• {log.timestamp}</span>
                        </div>
                        <div className="text-emerald-300 font-mono text-[11px] break-all leading-relaxed">
                          {log.sql}
                        </div>
                      </div>

                      <button
                        onClick={() => handleCopy(log.sql, idx)}
                        className="p-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 shrink-0 mt-1"
                        title="Copy SQL Query"
                      >
                        {copiedIndex === idx ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
                      </button>
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

        </div>
      </div>
    </div>
  );
}
